import { setTimeout } from 'node:timers/promises';
import type { AgentRunner } from '../../ports/agent-runner.js';

// Agent stand-in for document runs without network (AI-05): streams a few
// lines and answers with the package the task asks for, every file marked as
// demo output. Scenarios cover failures, a malformed or incomplete package
// and cancel through the delay.
export function createFakeDocumentRunner(
  options: {
    scenario?: 'success' | 'failure' | 'auth' | 'invalid-output' | 'incomplete';
    delayMs?: number;
  } = {},
): AgentRunner {
  const delayMs = options.delayMs ?? 0;
  return {
    async run(request) {
      const lines = [
        'Reading the input form and the pack…',
        'Auditing the program files…',
        'Writing the package…',
      ];
      for (const text of lines) {
        if (request.signal.aborted) return { status: 'cancelled' };
        try {
          await setTimeout(delayMs / lines.length, undefined, {
            signal: request.signal,
          });
        } catch {
          return { status: 'cancelled' };
        }
        request.onEvent?.({ kind: 'text', text });
      }
      const usage = {
        inputTokens: Math.ceil(request.prompt.length / 4),
        outputTokens: 300,
      };
      if (options.scenario === 'failure')
        return { status: 'failed', code: 'RUNNER_FAILED' };
      if (options.scenario === 'auth')
        return { status: 'failed', code: 'AGENT_AUTH_FAILED' };
      if (options.scenario === 'invalid-output')
        return {
          status: 'completed',
          rawOutput: 'I cannot help with that.',
          usage,
        };
      const files =
        /in this order: ([^\n]+?)\.\n/.exec(request.prompt)?.[1]?.split(', ') ??
        [];
      const state =
        options.scenario === 'incomplete' ? 'đang sinh' : 'hoàn tất';
      const blocks = files.map((name) => {
        const body = `# ${name.replace(/\.md$/, '')} — DEMO\n\n| Mục | Giá trị |\n| --- | --- |\n| Trạng thái sinh | ${state} |\n\n> Generated by the fake runner without AI. Not a real document.\n`;
        return `=== FILE: ${name} ===\n${body}\n=== END FILE ===`;
      });
      const rawOutput = blocks.join('\n');
      // Stream the answer in small pieces, like --include-partial-messages.
      for (let at = 0; at < rawOutput.length; at += 17)
        request.onEvent?.({
          kind: 'delta',
          text: rawOutput.slice(at, at + 17),
        });
      return { status: 'completed', rawOutput, usage };
    },
  };
}
