import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { setTimeout } from 'node:timers/promises';
import type { AgentRunner } from '../../ports/agent-runner.js';

// Agent stand-in for document runs without network (AI-05): streams a few
// lines and answers with the package the task asks for, every file marked as
// demo output. Scenarios cover failures, a malformed or incomplete package
// and cancel through the delay.
// Demo unit test specification built from the checklist the Portal wrote into
// the workspace: one or two cases per item, evidence copied from the item, so
// the package passes the validator (a stand-in for the agent, no AI).
function utSpec(
  workingDirectory: string | undefined,
  state: string,
  dropLast: boolean,
): string {
  const items = workingDirectory
    ? (
        JSON.parse(
          readFileSync(
            join(workingDirectory, 'context/p1/1.4-ut-skeleton.json'),
            'utf8',
          ),
        ) as {
          items: {
            id: string;
            kind: string;
            procedure: string;
            file: string;
            line: number;
            detail: string;
          }[];
        }
      ).items
    : [];
  const used = dropLast ? items.slice(0, -1) : items;
  let no = 0;
  const rows = used.flatMap((item) => {
    const cases =
      item.kind === 'procedure' || item.kind === 'event'
        ? ['正常系', '異常系']
        : ['正常系'];
    return cases.map((label) => {
      no += 1;
      return `| ${no} | ${item.id} | ${item.procedure} | ${item.detail} | ${label}（DEMO） | 前提条件（DEMO） | 入力データ（DEMO） | 手順（DEMO） | 期待結果（DEMO） | 確認観点（DEMO） | ${item.file}:${item.line} | テスト |  |`;
    });
  });
  return `# 単体テスト仕様書 — DEMO

| 項目 | 値 |
| --- | --- |
| Trạng thái sinh | ${state} |

> Generated by the fake runner without AI. Not a real document.

## テストケース

| No | 対象ID | 大項目 | 中項目 | 小項目 | 前提条件 | 入力データ | 手順 | 期待結果 | 確認観点 | 根拠(file:行) | 区分 | 対象外理由 |
| -- | ------ | ------ | ------ | ------ | -------- | ---------- | ---- | -------- | -------- | ------------- | ---- | ---------- |
${rows.join('\n')}

## Điểm chưa xác định

Không có
`;
}

// Demo integration test specification, the same way from the integration
// checklist: one scenario per item, the other program named where the item
// has one.
function itSpec(
  workingDirectory: string | undefined,
  state: string,
  dropLast: boolean,
): string {
  const items = workingDirectory
    ? (
        JSON.parse(
          readFileSync(
            join(workingDirectory, 'context/p1/1.5-it-skeleton.json'),
            'utf8',
          ),
        ) as {
          items: {
            id: string;
            kind: string;
            file: string;
            line: number;
            detail: string;
            counterparts: string[];
          }[];
        }
      ).items
    : [];
  const used = dropLast ? items.slice(0, -1) : items;
  const rows = used.map(
    (item, index) =>
      `| ${index + 1} | ${item.id} | ${item.kind} | シナリオ（DEMO） | ${item.detail}${item.counterparts[0] ? `、プログラム ${item.counterparts[0]}` : ''} | 前提条件（DEMO） | 手順（DEMO） | 期待結果（DEMO） | ${item.file}:${item.line} | テスト |  |`,
  );
  return `# 結合テスト仕様書 — DEMO

| 項目 | 値 |
| --- | --- |
| Trạng thái sinh | ${state} |

> Generated by the fake runner without AI. Not a real document.

## テストシナリオ

| No | 対象ID | 種別 | シナリオ | 関連要素 | 前提条件 | 手順 | 期待結果 | 根拠(file:行) | 区分 | 対象外理由 |
| -- | ------ | ---- | -------- | -------- | -------- | ---- | -------- | ------------- | ---- | ---------- |
${rows.join('\n')}

## Điểm chưa xác định

Không có
`;
}

export function createFakeDocumentRunner(
  options: {
    scenario?:
      | 'success'
      | 'failure'
      | 'auth'
      | 'invalid-output'
      | 'incomplete'
      // ut-test-spec leaves the last checklist item without a case
      | 'ut-missing-item'
      // it-test-spec leaves the last checklist item without a scenario
      | 'it-missing-item';
    delayMs?: number;
  } = {},
): AgentRunner {
  const delayMs = options.delayMs ?? 0;
  return {
    async run(request) {
      const lines = [
        'Reading the input form and the pack…',
        'Auditing the program files…',
        'Writing the package…',
      ];
      for (const text of lines) {
        if (request.signal.aborted) return { status: 'cancelled' };
        try {
          await setTimeout(delayMs / lines.length, undefined, {
            signal: request.signal,
          });
        } catch {
          return { status: 'cancelled' };
        }
        request.onEvent?.({ kind: 'text', text });
      }
      const usage = {
        inputTokens: Math.ceil(request.prompt.length / 4),
        outputTokens: 300,
      };
      if (options.scenario === 'failure')
        return { status: 'failed', code: 'RUNNER_FAILED' };
      if (options.scenario === 'auth')
        return { status: 'failed', code: 'AGENT_AUTH_FAILED' };
      if (options.scenario === 'invalid-output')
        return {
          status: 'completed',
          rawOutput: 'I cannot help with that.',
          usage,
        };
      const files =
        /in this order: ([^\n]+?)\.\n/.exec(request.prompt)?.[1]?.split(', ') ??
        [];
      const state =
        options.scenario === 'incomplete' ? 'đang sinh' : 'hoàn tất';
      const blocks = files.map((name) => {
        if (name === 'ut-test-spec.md')
          return `=== FILE: ${name} ===
${utSpec(request.workingDirectory, state, options.scenario === 'ut-missing-item')}
=== END FILE ===`;
        if (name === 'it-test-spec.md')
          return `=== FILE: ${name} ===
${itSpec(request.workingDirectory, state, options.scenario === 'it-missing-item')}
=== END FILE ===`;
        const body = `# ${name.replace(/\.md$/, '')} — DEMO\n\n| Mục | Giá trị |\n| --- | --- |\n| Trạng thái sinh | ${state} |\n\n> Generated by the fake runner without AI. Not a real document.\n`;
        return `=== FILE: ${name} ===\n${body}\n=== END FILE ===`;
      });
      const rawOutput = blocks.join('\n');
      // Stream the answer in small pieces, like --include-partial-messages.
      for (let at = 0; at < rawOutput.length; at += 17)
        request.onEvent?.({
          kind: 'delta',
          text: rawOutput.slice(at, at + 17),
        });
      return { status: 'completed', rawOutput, usage };
    },
  };
}
